#!/usr/bin/env bash
# Regenerates internal/protos from the Tesla Fleet Telemetry protos in
# Teslemetry/tesla-protocol at a pinned commit, with pinned protoc and
# protoc-gen-go versions, so the generated code is reproducible.
#
# Usage: scripts/generate.sh [tesla-protocol commit]
#
# To move to a newer tesla-protocol commit, run it with that commit, then update
# TESLA_PROTOCOL_COMMIT below to match and commit both.
set -euo pipefail

TESLA_PROTOCOL_COMMIT="${1:-e6f7afb1b633d7215e34d0cdac66dab983c6ae78}"
PROTOC_VERSION="36.2"
# protoc-gen-go is pinned by the "tool" directive in go.mod, at the same version
# as the google.golang.org/protobuf runtime the decoder links.

MODULE="github.com/Teslemetry/telemetry-decoder"
PACKAGE="internal/protos"
PROTOS=(vehicle_alert vehicle_connectivity vehicle_data vehicle_error vehicle_metric)

root="$(cd "$(dirname "$0")/.." && pwd)"
cache="${XDG_CACHE_HOME:-$HOME/.cache}/telemetry-decoder"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

case "$(uname -s)-$(uname -m)" in
  Linux-x86_64) platform=linux-x86_64 sha256=121f6c7afe1d4d0e3ea6aab9432038599250134cbf4474cb1167d2c7decd4278 ;;
  Linux-aarch64 | Linux-arm64) platform=linux-aarch_64 sha256=8b8f18bd2b30346efbc698dd5a73dd7c805f3ef8380f6dfc95c768f3f1852f6a ;;
  Darwin-*) platform=osx-universal_binary sha256=83d0dc80672f53486f54299bca6177159f9cad1fd54d4d3143eeea53c4423e1b ;;
  *) echo "generate.sh: no pinned protoc for $(uname -s)-$(uname -m)" >&2; exit 1 ;;
esac

protoc_dir="$cache/protoc-$PROTOC_VERSION-$platform"
if [[ ! -x "$protoc_dir/bin/protoc" ]]; then
  zip="$work/protoc.zip"
  curl -sSfL -o "$zip" \
    "https://github.com/protocolbuffers/protobuf/releases/download/v$PROTOC_VERSION/protoc-$PROTOC_VERSION-$platform.zip"
  echo "$sha256  $zip" | sha256sum -c --quiet - 2>/dev/null || echo "$sha256  $zip" | shasum -a 256 -c --quiet -
  rm -rf "$protoc_dir"
  mkdir -p "$protoc_dir"
  unzip -q "$zip" -d "$protoc_dir"
fi

curl -sSfL "https://codeload.github.com/Teslemetry/tesla-protocol/tar.gz/$TESLA_PROTOCOL_COMMIT" |
  tar -xz -C "$work" --strip-components=3 "tesla-protocol-$TESLA_PROTOCOL_COMMIT/proto/telemetry"

(cd "$root" && go build -o "$work/protoc-gen-go" google.golang.org/protobuf/cmd/protoc-gen-go)

# All the protos declare the fleet-telemetry go_package; map them to this module.
mappings=()
files=()
for proto in "${PROTOS[@]}"; do
  mappings+=("--go_opt=M$proto.proto=$MODULE/$PACKAGE;protos")
  files+=("$proto.proto")
done

rm -f "$root/$PACKAGE"/*.pb.go
mkdir -p "$root/$PACKAGE"
"$protoc_dir/bin/protoc" \
  --plugin=protoc-gen-go="$work/protoc-gen-go" \
  -I "$work" -I "$protoc_dir/include" \
  --go_out="$root" --go_opt=module="$MODULE" "${mappings[@]}" \
  "${files[@]}"

cat >"$root/$PACKAGE/source.go" <<EOF
// Code generated by scripts/generate.sh. DO NOT EDIT.

// Package protos holds the Tesla Fleet Telemetry messages, generated from
// https://github.com/Teslemetry/tesla-protocol/tree/$TESLA_PROTOCOL_COMMIT/proto/telemetry
package protos

// TeslaProtocolCommit is the tesla-protocol commit the messages are generated from.
const TeslaProtocolCommit = "$TESLA_PROTOCOL_COMMIT"
EOF
echo "Generated $PACKAGE from Teslemetry/tesla-protocol@$TESLA_PROTOCOL_COMMIT"
